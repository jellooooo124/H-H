"""DB-API compatibility layer for existing SQLite SQL, backed by a REAL psycopg3 connection.

One connection is deliberately shared by the single-worker educational API. For real
horizontal scaling use a transaction-scoped connection pool and verified advisory locks.
No fallback to SQLite is allowed if PostgreSQL was explicitly selected.
"""
import re

class PostgresCompat:
    def __init__(self, dsn):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError('PostgreSQL backend requires psycopg[binary]') from exc
        self.conn=psycopg.connect(dsn,autocommit=True,row_factory=dict_row,
                                  connect_timeout=8)
        self.is_postgres=True
        self.in_transaction=False
        self.conn.execute('SET statement_timeout = 30000')

    @staticmethod
    def convert(sql):
        # Only hard-coded application SQL is passed here; no user-provided SQL.
        sql=sql.strip()
        sql=sql.replace('BEGIN IMMEDIATE','BEGIN')
        sql=re.sub(r'\bINSERT OR IGNORE INTO\b','INSERT INTO',sql,flags=re.I)
        sql=sql.replace('?', '%s')
        sql=sql.replace('status="TRIAGED"',"status='TRIAGED'")
        return sql

    def execute(self, sql, params=()):
        raw=sql.strip()
        ignore=bool(re.search(r'^INSERT\s+OR\s+IGNORE\s+INTO\b',raw,re.I))
        normalized=self.convert(raw)
        if ignore: normalized+=' ON CONFLICT DO NOTHING'
        cur=self.conn.execute(normalized,params)
        if normalized.upper()=='BEGIN': self.in_transaction=True
        elif normalized.upper() in ('COMMIT','ROLLBACK'): self.in_transaction=False
        return cur

    def executescript(self, script):
        ddl=re.sub(r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b',
                   'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',script,flags=re.I)
        ddl=re.sub(r'\bREAL\b','DOUBLE PRECISION',ddl,flags=re.I)
        for part in ddl.split(';'):
            if part.strip(): self.execute(part)

    def close(self):
        self.conn.close()
