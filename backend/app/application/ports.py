"""Technology-independent application ports for the bounded migration slices."""
from __future__ import annotations
from typing import Protocol, Any

class CheckinEventDispatcher(Protocol):
    async def dispatch_checkin(self,event_id:str) -> None:
        """Schedule ID-only check-in processing. Failure is handled by the outbox."""

class PatientAssignments(Protocol):
    def is_assigned(self,clinician_sub:str,patient_ref:str) -> bool: ...
    def assignments(self,clinician_sub:str) -> set[str]: ...

class CaseReadRepository(Protocol):
    def get(self,case_id:str) -> dict[str,Any]: ...
    def list_cases(self,patient_refs=None) -> list[dict[str,Any]]: ...
    def audit_events(self,case_id:str) -> list[dict[str,Any]]: ...
    def verify_audit(self) -> bool: ...
    def list_outbox(self,patient_refs=None) -> list[dict[str,Any]]: ...
