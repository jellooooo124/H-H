"""Technology-independent application ports for the bounded migration slices."""
from __future__ import annotations
from typing import Protocol, Any

class CheckinEventDispatcher(Protocol):
    async def dispatch_checkin(self,event_id:str) -> None:
        """Schedule ID-only check-in processing. Failure is handled by the outbox."""

class PatientAssignments(Protocol):
    def is_assigned(self,clinician_sub:str,patient_ref:str) -> bool: ...
    def assignments(self,clinician_sub:str) -> set[str]: ...

class CaseReadRepository(Protocol):
    def get(self,case_id:str) -> dict[str,Any]: ...
    def list_cases(self,patient_refs=None) -> list[dict[str,Any]]: ...
    def audit_events(self,case_id:str) -> list[dict[str,Any]]: ...
    def verify_audit(self) -> bool: ...
    def list_outbox(self,patient_refs=None) -> list[dict[str,Any]]: ...

class CaseEventDispatcher(Protocol):
    async def dispatch_case(self,case_id:str) -> None: ...

class CheckinStatusReader(Protocol):
    def checkin_status(self,event_id:str) -> str | None: ...

class ClinicalCaseRepository(Protocol):
    def transaction(self) -> Any: ...
    def create(self,case_id:str,patient_ref:str,payload:dict) -> None: ...
    def get(self,case_id:str) -> dict[str,Any]: ...
    def save(self,case:dict,event:str,actor:str='system',metadata:dict|None=None) -> dict[str,Any]: ...
    def remove_image(self,case:dict) -> None: ...
    def list_cases(self,patient_refs=None) -> list[dict[str,Any]]: ...
    def outbox_insert(self,case:dict,content:str) -> Any: ...
    def audit(self,case_id:str,event:str,actor:str,metadata:dict|None=None) -> None: ...

class ClinicalTaskCoordinator(Protocol):
    def new_task(self,*args,**kwargs) -> Any: ...
    def require_review_claim(self,case_id:str,actor:str) -> Any: ...
    def complete_review(self,case_id:str,actor:str,choice:str) -> Any: ...
    def task_for_case(self,case_id:str) -> dict[str,Any]: ...
    def summary(self,patient_ref:str) -> dict[str,Any]: ...
